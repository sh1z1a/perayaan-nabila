const notePage = document.getElementById('note-page');
const noteSender = document.getElementById('note-sender');
const noteMessage = document.getElementById('note-message');
const notePageNumber = document.getElementById('note-page-number');
const notePageStatus = document.getElementById('notes-page-status');
const previousNoteButton = document.getElementById('notes-prev');
const nextNoteButton = document.getElementById('notes-next');
let currentNoteIndex = 0;
let isTurningPage = false;

function renderNotePage() {
    const note = siteData.notes[currentNoteIndex];
    noteSender.textContent = `From: ${note.sender} ✿`;
    noteMessage.textContent = note.full;
    notePageNumber.textContent = String(currentNoteIndex + 1).padStart(2, '0');
    notePageStatus.textContent = `Page ${currentNoteIndex + 1} of ${siteData.notes.length}`;
    notePage.scrollTop = 0;
    previousNoteButton.disabled = currentNoteIndex === 0 || isTurningPage;
    nextNoteButton.disabled = currentNoteIndex === siteData.notes.length - 1 || isTurningPage;
}

function turnNotePage(direction) {
    if (isTurningPage) return;

    const nextIndex = currentNoteIndex + direction;
    if (nextIndex < 0 || nextIndex >= siteData.notes.length) return;

    isTurningPage = true;
    notePage.classList.remove('turn-forward', 'turn-back');
    notePage.classList.add(direction > 0 ? 'turn-forward' : 'turn-back');
    renderNotePage();

    window.setTimeout(() => {
        currentNoteIndex = nextIndex;
        renderNotePage();
    }, 210);

    window.setTimeout(() => {
        notePage.classList.remove('turn-forward', 'turn-back');
        isTurningPage = false;
        renderNotePage();
    }, 420);
}

previousNoteButton.addEventListener('click', () => turnNotePage(-1));
nextNoteButton.addEventListener('click', () => turnNotePage(1));
renderNotePage();

